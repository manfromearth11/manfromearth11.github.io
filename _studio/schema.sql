CREATE TABLE IF NOT EXISTS oauth_states (id TEXT PRIMARY KEY, verifier TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, token TEXT NOT NULL, csrf TEXT NOT NULL, owner TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS bridges (id TEXT PRIMARY KEY, session TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS navigation (id TEXT PRIMARY KEY, session TEXT NOT NULL, expires INTEGER NOT NULL);
